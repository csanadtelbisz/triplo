#!/usr/bin/env python3
"""Generate src/generated/data.ts from the CSV/JSON files in data/. Usage: python3 -I build-json.py <data dir> <out data.ts>"""
import csv, hashlib, json, os, sys
from collections import defaultdict

d, out = sys.argv[1], sys.argv[2]
def rd(name):
    return list(csv.DictReader(open(os.path.join(d, name), newline="", encoding="utf-8")))

factors = defaultdict(list)
for r in rd("defra-factors.csv"):
    factors[r["key"]].append([int(r["year"]), float(r["value"])])
grid = defaultdict(list)
for r in rd("grid-intensity.csv"):
    grid[r["iso3"]].append([int(r["year"]), float(r["gco2e_per_kwh"])])
regions = {r["iso3"]: r["continent"] for r in rd("country-region.csv")}
aircraft = [{"model": r["model"], "icao": r["icao"].split(";"), "bodyType": r["body_type"], "band": r["band"],
             "seats": int(r["seats"]), "loadFactor": float(r["load_factor"]),
             "kgCo2PerVkm": float(r["kg_co2_per_vkm"]), "avgFlightKm": int(r["avg_flight_km"])} for r in rd("aircraft.csv")]
operators = {r["operator"]: {"name": r["name"], "loadFactor": float(r["load_factor"])} for r in rd("operators.csv")}
layouts = [{"operator": r["operator"], "aircraft": r["aircraft"], "seats": {k: int(r[k] or 0) for k in ("economy", "premium_economy", "business", "first")}} for r in rd("operator-layouts.csv")]
params = json.load(open(os.path.join(d, "flight-params.json")))
params = {k: v for k, v in params.items() if not k.startswith("_")}

def j(x): return json.dumps(x, separators=(",", ":"), ensure_ascii=False)
version = "factors:" + ",".join(sorted({str(y) for v in factors.values() for y, _ in v})) + " grid:" + str(max(y for v in grid.values() for y, _ in v))
revision = hashlib.sha256(json.dumps([factors, grid, regions, aircraft, operators, layouts, params], sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")).hexdigest()
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by scripts/build-json.py from data/*. Do not edit by hand.\n")
    f.write("import type { DataBundle } from \"../data\";\n\n")
    f.write(f"export const climateDataRevision = {j(revision)};\n\n")
    f.write("export const defaultData: DataBundle = {\n")
    f.write(f"  version: {j(version)},\n")
    f.write(f"  factors: {j(factors)},\n")
    f.write(f"  grid: {j(grid)},\n")
    f.write(f"  regions: {j(regions)},\n")
    f.write(f"  aircraft: {j(aircraft)},\n")
    f.write(f"  operators: {j(operators)},\n")
    f.write(f"  layouts: {j(layouts)},\n")
    f.write(f"  flight: {j(params)},\n")
    f.write("};\n")
print("wrote", out, os.path.getsize(out), "bytes;", version)
